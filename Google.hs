getItems :: Pairs -> String -> [FilePath]
getItems pairs key = dedup ( map (snd) (filter(\x -> fst x == key ) pairs) ) -- based on the key get all the filepath then remove duplicated and return it as a list of filepath only for one key

getKeys ::  Pairs -> [String]
getKeys [] = []
getKeys (xs) =  dedup (mergeSort (map fst xs)) -- first sort keys (words) then remove duplicated and return it as a list of string

mergeBackPairs :: [String] -> [[FilePath]] -> Table
mergeBackPairs [] [] = []
mergeBackPairs [] _ = []
mergeBackPairs _ [] = []
mergeBackPairs (key : keys) (item : items) = (key, item) : mergeBackPairs (keys) (items)  -- give it a sorted list of name (words) and [items (filepath)] because they have been sorted before (each key has the same index as items ) we merge these keys and items



