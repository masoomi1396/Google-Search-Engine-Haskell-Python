merge_1 :: Ord a => [a] -> [a] -> [a]
merge_1 [] xs = xs
merge_1 xs [] = xs
merge_1 (x:xs) (y:ys) | x >= y = y : merge_1 (x:xs) (ys)
                     | otherwise = x : merge_1 (xs) (y:ys)

mergeSort :: Ord a => [a] ->[a]
mergeSort [] = []
mergeSort [x] = [x]
mergeSort xs = merge_1 firstHalf secondHalf
   where 
      firstHalf = mergeSort (take (length xs `div` 2 ) (xs))
      secondHalf = mergeSort (drop (length xs `div` 2) (xs))

myElem_2 :: Eq a => a -> [a] -> Bool
myElem_2 m [] = False
myElem_2 m (x:xs) | m == x = True
                | otherwise = myElem_2 m (xs)

dedup :: Eq a => [a] -> [a]
dedup [] = []
dedup (x:xs) | myElem_2 x (xs) == True = dedup (xs)
             | otherwise = x: dedup (xs)


isDistinctNaive :: Eq a => [a] -> Bool
isDistinctNaive [] = True
isDistinctNaive (x:xs) | length (filter (==x) xs) > 0 = False
                    | otherwise = isDistinctNaive xs

