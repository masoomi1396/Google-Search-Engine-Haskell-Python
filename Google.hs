makePairs :: [FilePath] -> IO Pairs
makePairs args = do
    ftab <- zip args . map words <$> mapM readFile args
    return [ (w,n) | (n,ws) <- ftab, w<-ws ]

prompt :: String -> IO String
prompt msg = do
    putStr $ msg ++ ": "
    handle handler getLine where
        handler e
            | isEOFError e = return ""
            | otherwise    = throwIO e




replLoop :: Table -> IO ()
replLoop tab = go
    where
        go = do
            w <- prompt "Search term"
            if null w then
                return ()
            else do
                let files = basicLookup tab w
                print files
                go



main :: IO ()
main = do
    args <- getArgs
    when (null args) (fail "No filenames provided")

    pairs <- makePairs args
    let tab = makeTable pairs
    replLoop tab

