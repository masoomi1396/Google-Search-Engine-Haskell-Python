isValidTable :: Table -> Bool
isValidTable [] = True
isValidTable tab = (isDuplicatedKeys tab) && (isDuplicatedFilenames tab) && (noEmptyLists tab)   -- Check is there any duplicated keys and is there any duplicated filenames for each key and is there any empty list for each key

isDuplicatedKeys :: Table -> Bool
isDuplicatedKeys [] = True
isDuplicatedKeys (tab) = isDistinctNaive (map fst tab) -- Returns True if there is no duplicated Keys

noEmptyLists :: Table -> Bool
noEmptyLists [] = True
noEmptyLists ((key, filenames):xs) = filenames /= [] && noEmptyLists xs -- return True if there is no empty list for filenames for each key

isDuplicatedFilenames :: Table -> Bool
isDuplicatedFilenames [] = True
isDuplicatedFilenames ((key, filenames):xs) = isDistinctNaive filenames && isDuplicatedFilenames xs -- check there is no duplicated name in filenames for each key

